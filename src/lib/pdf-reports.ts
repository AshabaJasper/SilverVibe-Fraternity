export interface StatementLine {
  label: string;
  amount: number;
}

export async function generateIncomeStatement(
  income: StatementLine[] = [
    { label: "Interest income — loans", amount: 412_500_000 },
    { label: "Interest income — investments", amount: 96_000_000 },
    { label: "Membership & entrance fees", amount: 18_400_000 },
    { label: "Loan processing fees", amount: 31_200_000 },
  ],
  expenses: StatementLine[] = [
    { label: "Interest on member savings", amount: 168_000_000 },
    { label: "Salaries & benefits", amount: 142_000_000 },
    { label: "Office rent & utilities", amount: 38_600_000 },
    { label: "Loan loss provision", amount: 21_500_000 },
    { label: "Administration & IT", amount: 26_900_000 },
  ]
) {
  const ti = income.reduce((a, l) => a + l.amount, 0);
  const te = expenses.reduce((a, l) => a + l.amount, 0);
  await generateTablePdf({
    title: "Income Statement",
    subtitle: periodLabel(),
    filename: `income-statement-${stamp()}`,
    summary: [
      ["Total income", ugx(ti)],
      ["Total expenses", ugx(te)],
      ["Net surplus", ugx(ti - te)],
    ],
    sections: [
      {
        heading: "Income",
        columns: ["Line item", "Amount (UGX)"],
        rows: [...income.map((l) => [l.label, l.amount]), ["Total income", ti]],
        boldRows: [income.length],
        numericCols: [1],
      },
      {
        heading: "Expenses",
        columns: ["Line item", "Amount (UGX)"],
        rows: [...expenses.map((l) => [l.label, l.amount]), ["Total expenses", te], ["Net surplus", ti - te]],
        boldRows: [expenses.length, expenses.length + 1],
        numericCols: [1],
      },
    ],
  });
}

export async function generateBalanceSheet(
  assets: StatementLine[] = [
    { label: "Cash & bank balances", amount: 610_000_000 },
    { label: "Loans to members (net)", amount: ADMIN_KPI.total_loan_book.value - 43_000_000 },
    { label: "Investments & fixed deposits", amount: 2_980_000_000 },
    { label: "Property & equipment", amount: 340_000_000 },
    { label: "Other receivables", amount: 63_000_000 },
  ],
  liabilities: StatementLine[] = [
    { label: "Member savings deposits", amount: ADMIN_KPI.total_savings.value },
    { label: "Accrued interest payable", amount: 42_000_000 },
    { label: "Other payables", amount: 38_000_000 },
  ],
  equity: StatementLine[] = [
    { label: "Share capital", amount: ADMIN_KPI.total_share_capital.value },
  ]
) {
  const ta = assets.reduce((a, l) => a + l.amount, 0);
  const tl = liabilities.reduce((a, l) => a + l.amount, 0);
  const eqBase = equity.reduce((a, l) => a + l.amount, 0);
  // Retained surplus balances the sheet.
  const retained = ta - tl - eqBase;
  const eqLines = [...equity, { label: "Retained surplus & reserves", amount: retained }];
  const te = eqBase + retained;
  await generateTablePdf({
    title: "Statement of Financial Position",
    subtitle: `As at ${formatDate(new Date())}`,
    filename: `balance-sheet-${stamp()}`,
    summary: [
      ["Total assets", ugx(ta)],
      ["Total liabilities", ugx(tl)],
      ["Total equity", ugx(te)],
    ],
    sections: [
      { heading: "Assets", columns: ["Account", "Amount (UGX)"], rows: [...assets.map((l) => [l.label, l.amount]), ["Total assets", ta]], boldRows: [assets.length], numericCols: [1] },
      { heading: "Liabilities", columns: ["Account", "Amount (UGX)"], rows: [...liabilities.map((l) => [l.label, l.amount]), ["Total liabilities", tl]], boldRows: [liabilities.length], numericCols: [1] },
      { heading: "Equity", columns: ["Account", "Amount (UGX)"], rows: [...eqLines.map((l) => [l.label, l.amount]), ["Total equity", te], ["Liabilities + equity", tl + te]], boldRows: [eqLines.length, eqLines.length + 1], numericCols: [1] },
    ],
  });
}

