export interface StatementTxn {
  date: string;
  type: string;
  account: string;
  amount: number;
  direction: string;
  channel?: string;
}

export async function generateMemberStatement(
  member: { name: string; sv: string; email?: string; phone?: string },
  transactions: StatementTxn[],
  balances?: { label: string; amount: number }[]
) {
  const credits = transactions.filter((t) => t.direction === "credit").reduce((a, t) => a + t.amount, 0);
  const debits = transactions.filter((t) => t.direction !== "credit").reduce((a, t) => a + t.amount, 0);
  await generateTablePdf({
    title: "Member Account Statement",
    subtitle: `${member.name} · ${member.sv}`,
    filename: `statement-${member.sv}-${stamp()}`,
    summary: [
      ["Member", `${member.name} (${member.sv})`],
      ...(member.phone ? ([["Phone", member.phone]] as [string, string][]) : []),
      ["Total credits", ugx(credits)],
      ["Total debits", ugx(debits)],
    ],
    sections: [
      ...(balances?.length
        ? [{ heading: "Account balances", columns: ["Account", "Balance (UGX)"], rows: balances.map((b) => [b.label, b.amount] as Cell[]), numericCols: [1] }]
        : []),
      {
        heading: "Transactions",
        columns: ["Date", "Type", "Account", "Channel", "Debit", "Credit"],
        rows: transactions.length
          ? transactions.map((t) => [formatDate(t.date), t.type, t.account, t.channel ?? "-", t.direction === "credit" ? "-" : t.amount, t.direction === "credit" ? t.amount : "-"])
          : [["-", "No transactions in this period", "", "", "", ""]],
        numericCols: [4, 5],
      },
    ],
  });
}

export async function generateLoanSchedulePdf(
  loan: { loan_number: string; product: string; principal: number; interest_rate: string; member?: string },
  schedule: { installment: number; due_date: string; principal: number; interest: number; total: number; status: string }[]
) {
  const tp = schedule.reduce((a, s) => a + s.principal, 0);
  const ti = schedule.reduce((a, s) => a + s.interest, 0);
  await generateTablePdf({
    title: "Loan Repayment Schedule",
    subtitle: `${loan.loan_number} · ${loan.product}${loan.member ? ` · ${loan.member}` : ""}`,
    filename: `loan-schedule-${loan.loan_number}`,
    summary: [
      ["Principal", ugx(loan.principal)],
      ["Interest rate", `${loan.interest_rate} p.a. (reducing balance)`],
      ["Total interest", ugx(ti)],
      ["Total repayable", ugx(tp + ti)],
    ],
    sections: [
      {
        columns: ["#", "Due date", "Principal", "Interest", "Installment", "Status"],
        rows: [...schedule.map((s) => [s.installment, formatDate(s.due_date), s.principal, s.interest, s.total, s.status]), ["", "Totals", tp, ti, tp + ti, ""]],
        boldRows: [schedule.length],
        numericCols: [2, 3, 4],
      },
    ],
  });
}

/** A one-page landscape share certificate. */
export async function generateShareCertificate(cert: {
  number: string;
  holder: string;
  sv: string;
  shares: number;
  amount: number;
  date: string;
}) {
  const { jsPDF } = await loadJsPdf();
  const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  doc.setDrawColor(192, 192, 192);
  doc.setLineWidth(2);
  doc.rect(10, 10, w - 20, h - 20);
  doc.setLineWidth(0.5);
  doc.rect(14, 14, w - 28, h - 28);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(24);
  doc.setTextColor(...BRAND);
  doc.text(SACCO_NAME, w / 2, 40, { align: "center" });
  doc.setFontSize(14);
  doc.setTextColor(...ACCENT);
  doc.text("SHARE CERTIFICATE", w / 2, 52, { align: "center" });

  doc.setFont("helvetica", "normal");
  doc.setFontSize(12);
  doc.setTextColor(60, 60, 60);
  doc.text("This is to certify that", w / 2, 75, { align: "center" });
  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.setTextColor(...BRAND);
  doc.text(cert.holder, w / 2, 90, { align: "center" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(12);
  doc.setTextColor(60, 60, 60);
  doc.text(`Member No. ${cert.sv}`, w / 2, 99, { align: "center" });
  doc.text(
    `is the registered holder of ${num(cert.shares)} fully paid ordinary shares, valued at ${ugx(cert.amount)},`,
    w / 2,
    114,
    { align: "center" }
  );
  doc.text("subject to the by-laws of the Society.", w / 2, 122, { align: "center" });

  doc.setFontSize(10);
  doc.text(`Certificate No. ${cert.number}`, 30, h - 40);
  doc.text(`Date of issue: ${formatDate(cert.date)}`, 30, h - 33);
  doc.line(w - 110, h - 40, w - 30, h - 40);
  doc.text("Chairperson, Board of Directors", w - 70, h - 34, { align: "center" });

  doc.save(`share-certificate-${cert.number}.pdf`);
}

