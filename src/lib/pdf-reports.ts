const SACCO_NAME = "SilverVibe Fraternity Cooperative Society Ltd";
const SACCO_ADDRESS = "Plot 22, Kampala Road · Kampala, Uganda · info@silvervibe.coop";
const BRAND: [number, number, number] = [26, 26, 26];
const ACCENT: [number, number, number] = [74, 144, 217];

/** Plain number with thousands separators (PDF core fonts lack some currency glyphs). */
const ugx = (n: number) => `UGX ${Math.round(n).toLocaleString("en-US")}`;
const num = (n: number) => Math.round(n).toLocaleString("en-US");

export type Cell = string | number;
export interface PdfSection {
  heading?: string;
  columns: string[];
  rows: Cell[][];
  /** Bold rows (e.g. totals) by index. */
  boldRows?: number[];
  /** Right-align these column indexes. */
  numericCols?: number[];
}
export interface PdfOptions {
  title: string;
  subtitle?: string;
  filename: string;
  /** Key/value summary block printed under the header. */
  summary?: [string, string][];
  sections: PdfSection[];
  orientation?: "portrait" | "landscape";
  footerNote?: string;
}

async function loadJsPdf() {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import("jspdf"), import("jspdf-autotable")]);
  return { jsPDF, autoTable };
}

function header(doc: JsPDF, title: string, subtitle?: string): number {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(...BRAND);
  doc.rect(0, 0, w, 28, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text(SACCO_NAME, 14, 13);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  doc.setTextColor(192, 192, 192);
  doc.text(SACCO_ADDRESS, 14, 20);

  doc.setTextColor(...BRAND);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text(title, 14, 42);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9.5);
  doc.setTextColor(100, 116, 139);
  let y = 48;
  if (subtitle) {
    doc.text(subtitle, 14, y);
    y += 5;
  }
  doc.text(`Generated ${new Date().toLocaleString("en-GB")}`, 14, y);
  return y + 6;
}

function footer(doc: JsPDF, note?: string) {
  const pages = doc.getNumberOfPages();
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(note ?? "Demo document — generated by the SilverVibe SACCO showcase", 14, h - 8);
    doc.text(`Page ${i} of ${pages}`, w - 14, h - 8, { align: "right" });
  }
}

/** Generic multi-section table PDF. Every named report below is built on this. */
export async function generateTablePdf(opts: PdfOptions): Promise<void> {
  const { jsPDF, autoTable } = await loadJsPdf();
  const doc = new jsPDF({ orientation: opts.orientation ?? "portrait", unit: "mm", format: "a4" });
  let y = header(doc, opts.title, opts.subtitle);

  if (opts.summary?.length) {
    autoTable(doc, {
      startY: y,
      body: opts.summary,
      theme: "plain",
      styles: { fontSize: 9.5, cellPadding: 1.5 },
      columnStyles: { 0: { textColor: [100, 116, 139], cellWidth: 55 }, 1: { fontStyle: "bold", textColor: BRAND } },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 6;
  }

  for (const s of opts.sections) {
    if (s.heading) {
      if (y > doc.internal.pageSize.getHeight() - 40) {
        doc.addPage();
        y = 20;
      }
      doc.setFont("helvetica", "bold");
      doc.setFontSize(11);
      doc.setTextColor(...BRAND);
      doc.text(s.heading, 14, y);
      y += 3;
    }
    const numeric = new Set(s.numericCols ?? []);
    const bold = new Set(s.boldRows ?? []);
    autoTable(doc, {
      startY: y,
      head: [s.columns],
      body: s.rows.map((r) => r.map((c) => (typeof c === "number" ? num(c) : c))),
      theme: "striped",
      headStyles: { fillColor: ACCENT, textColor: 255, fontStyle: "bold", fontSize: 9 },
      styles: { fontSize: 8.5, cellPadding: 2.2 },
      margin: { left: 14, right: 14 },
      didParseCell: (data) => {
        if (numeric.has(data.column.index)) data.cell.styles.halign = "right";
        if (data.section === "body" && bold.has(data.row.index)) data.cell.styles.fontStyle = "bold";
      },
    });
    y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 10;
  }

  footer(doc, opts.footerNote);
  doc.save(opts.filename.endsWith(".pdf") ? opts.filename : `${opts.filename}.pdf`);
}

const stamp = () => new Date().toISOString().slice(0, 10);
const periodLabel = () => `For the period ended ${formatDate(new Date())}`;

