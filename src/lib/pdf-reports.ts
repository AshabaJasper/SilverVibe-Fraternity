// ============================================================
// PDF generation (jsPDF + autotable).
//
// jsPDF is imported lazily inside each function so it is only downloaded
// when a user actually clicks "Download PDF" — it never runs during SSR
// and does not bloat the initial page bundle.
// ============================================================
