export async function generateTrialBalance(rows: { code: string; name: string; debit: number; credit: number }[]) {
  const td = rows.reduce((a, r) => a + r.debit, 0);
  const tc = rows.reduce((a, r) => a + r.credit, 0);
  await generateTablePdf({
    title: "Trial Balance",
    subtitle: `As at ${formatDate(new Date())}`,
    filename: `trial-balance-${stamp()}`,
    summary: [
      ["Total debits", ugx(td)],
      ["Total credits", ugx(tc)],
      ["Status", td === tc ? "Balanced" : `Out of balance by ${ugx(Math.abs(td - tc))}`],
    ],
    sections: [
      {
        columns: ["Code", "Account", "Debit (UGX)", "Credit (UGX)"],
        rows: [...rows.map((r) => [r.code, r.name, r.debit || "-", r.credit || "-"]), ["", "Totals", td, tc]],
        boldRows: [rows.length],
        numericCols: [2, 3],
      },
    ],
  });
}

